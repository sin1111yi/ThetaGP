#!/usr/bin/env python3
"""Writes a self-signed key for exercising the PS4 authentication channel.

The key this produces is test material: it proves the channel and the signature
flow end to end, and no console accepts it. The header it writes is compiled only
when THETAGP_PS4_TEST_KEY is set.
"""

import pathlib
import sys

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import padding, rsa

OUT = pathlib.Path("src/drivers/gp_emulator/ps4/ps4_test_key.h")


def be(value: int, size: int) -> bytes:
    return value.to_bytes(size, "big")


def array(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02X}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{body}}};"


def main() -> int:
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    numbers = key.private_numbers()
    public = numbers.public_numbers
    serial = bytes(range(16))
    modulus = be(public.n, 256)
    exponent = be(public.e, 256)
    certificate = key.sign(
        serial + modulus + exponent,
        padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32),
        hashes.SHA256(),
    )

    parts = [
        "// Test material, generated by scripts/crypto/gen_ps4_test_key.py.",
        "//",
        "// The key is its own, and signs its own certificate: the signature flow",
        "// is real and no console accepts the result. Compiled only when",
        "// THETAGP_PS4_TEST_KEY is set.",
        "",
        "#pragma once",
        "",
        '#include "drivers/gp_emulator/ps4/ps4_auth.h"',
        "",
        "namespace ThetaGP::Drivers::GPEmulator {",
        "",
        array("ps4_test_key_serial", serial),
        array("ps4_test_key_modulus", modulus),
        array("ps4_test_key_exponent", exponent),
        array("ps4_test_key_prime_p", be(numbers.p, 128)),
        array("ps4_test_key_prime_q", be(numbers.q, 128)),
        array("ps4_test_key_certificate", certificate),
        "",
        "static const Ps4AuthKey kPs4TestKey = {",
        "    .serial = ps4_test_key_serial,",
        "    .modulus = ps4_test_key_modulus,",
        "    .exponent = ps4_test_key_exponent,",
        "    .prime_p = ps4_test_key_prime_p,",
        "    .prime_q = ps4_test_key_prime_q,",
        "    .certificate = ps4_test_key_certificate,",
        "};",
        "",
        "} // namespace ThetaGP::Drivers::GPEmulator",
        "",
    ]
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
